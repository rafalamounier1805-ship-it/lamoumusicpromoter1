async function computeRealHooks(file,duration){
  const Ctx=window.AudioContext||window.webkitAudioContext;if(!Ctx)return[];
  const ctx=new Ctx();
  try{
    const buf=await ctx.decodeAudioData(await file.arrayBuffer());
    const sr=buf.sampleRate, len=buf.length, channels=buf.numberOfChannels, frame=Math.max(256,Math.floor(sr*.25));
    const env=[];
    for(let i=0;i<len;i+=frame){let sum=0,n=0;for(let j=i;j<Math.min(len,i+frame);j+=16){let s=0;for(let c=0;c<channels;c++)s+=buf.getChannelData(c)[j]||0;s/=Math.max(1,channels);sum+=s*s;n++}env.push(Math.sqrt(sum/Math.max(1,n)))}
    if(!env.length)return[];
    const frames=Math.max(1,Math.round(duration/.25)),step=Math.max(1,Math.round(1/.25)),candidates=[];
    for(let i=0;i<env.length;i+=step){const end=Math.min(env.length,i+frames);if(end-i<Math.max(2,frames*.55))break;let energy=0,transient=0;for(let k=i;k<end;k++){energy+=env[k];if(k>i)transient+=Math.max(0,env[k]-env[k-1])}energy/=(end-i);transient/=Math.max(1,end-i-1);candidates.push({i,energy,transient})}
    const maxE=Math.max(...candidates.map(x=>x.energy),1e-6),maxT=Math.max(...candidates.map(x=>x.transient),1e-6);
    for(const x of candidates)x.score=.72*(x.energy/maxE)+.28*(x.transient/maxT);
    candidates.sort((a,b)=>b.score-a.score);
    const chosen=[];
    for(const x of candidates){const start=x.i*.25;if(chosen.some(y=>Math.abs(y.start-start)<duration*.6))continue;chosen.push({start:Math.round(start*2)/2,end:Math.min(buf.duration,Math.round(start*2)/2+duration),score:x.score});if(chosen.length===3)break}
    return chosen;
  }finally{await ctx.close().catch(()=>{})}
}
