function mergeState(remote){
  const local=read();
  const rh=Array.isArray(remote?.history)?remote.history:[], lh=Array.isArray(local.history)?local.history:[];
  const rs=Array.isArray(remote?.suppressed)?remote.suppressed:[], ls=Array.isArray(local.suppressed)?local.suppressed:[];
  const rr=Array.isArray(remote?.rankings)?remote.rankings:[], lr=Array.isArray(local.rankings)?local.rankings:[];
  const union=(a,b,key='id')=>{
    const m=new Map();for(const x of a||[])if(x&&x[key]!=null)m.set(String(x[key]),x);for(const x of b||[])if(x&&x[key]!=null)m.set(String(x[key]),{...(m.get(String(x[key]))||{}),...x});return [...m.values()];
  };
  const next={...local,history:union(rh,lh),suppressed:union(rs,ls,'channelId'),rankings:union(rr,lr)};
  const before=JSON.stringify({history:lh,suppressed:ls,rankings:lr});
  const after=JSON.stringify({history:next.history,suppressed:next.suppressed,rankings:next.rankings});
  if(before!==after){write(next);return true}return false;
}
